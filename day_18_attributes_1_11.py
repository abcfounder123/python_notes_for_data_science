class Tires:
    def __init__(self, size):
        self.size = size
        self.pressure = 0

    def pump(self, p):
        self.pressure = p
        print(f"pump to {p} psi.")

    def __repr__(self):
        return f"{self.size} inches tires"


class Engine:
    def __init__(self, fuel_type):
        self.fuel_type = fuel_type
        self.state = "off"

    def on(self):
        if self.state == "off":
            self.state = "on"
            print("Engine On.")
        else:
            print("Already on.")
            
    def off(self):
        if self.state == "on":
            self.state = "off"
            print("Engine Off.")
        else:
            print("Already off.")

    def __repr__(self):
        return f"{self.fuel_type} engine({self.state})"


class Car:
    n = 0
    def __init__(self, tires, engine):
        Car.n += 1
        self.VIN = f"BMW-{Car.n:0>4}"
        self.tires = tires
        self.engine = engine

    def __repr__(self):
        return f"{self.VIN}({self.engine})"


